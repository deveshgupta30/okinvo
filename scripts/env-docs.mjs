// Generates the configuration reference in README.md from src/lib/env.schema.ts (the contract)
// and the comments in .env.example, between the markers
//   <!-- env-docs:start --> … <!-- env-docs:end -->
//
//   pnpm env:docs            rewrite the table
//   pnpm env:docs:check      exit 1 when README.md is stale (CI)
//
// `renderEnvDocs(schemaSource, envExample)` is pure so it is unit-tested; the test also proves
// every schema key appears in the committed README.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const ROOT = path.resolve(here, "..");
export const README = path.join(ROOT, "README.md");
export const SCHEMA = path.join(ROOT, "src", "lib", "env.schema.ts");
export const ENV_EXAMPLE = path.join(ROOT, ".env.example");
export const START = "<!-- env-docs:start -->";
export const END = "<!-- env-docs:end -->";

/** `KEY=value   # comment` lines of .env.example → { KEY: { value, comment } }. */
export function parseEnvExample(text) {
  const out = {};
  for (const raw of text.split("\n")) {
    const line = raw.replace(/^#\s?(?=[A-Z0-9_]+=)/, ""); // commented-out keys still document
    const m = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
    if (!m) continue;
    let rest = m[2];
    let comment = "";
    const hash = rest.indexOf("#");
    if (hash >= 0) {
      comment = rest.slice(hash + 1).trim();
      rest = rest.slice(0, hash);
    }
    out[m[1]] = { value: rest.trim().replace(/^"|"$/g, ""), comment };
  }
  return out;
}

/** The `KEY: z…` entries of the schema's z.object literal, with their doc comments. */
export function parseSchema(source) {
  const entries = [];
  const lines = source.split("\n");
  let pendingDoc = "";
  let inObject = false;
  let current = null;
  for (const line of lines) {
    if (!inObject) {
      if (/^\s*\.object\(\{\s*$/.test(line) || /z\s*\.object\(\{\s*$/.test(line)) inObject = true;
      continue;
    }
    if (/^\s*\}\)\s*$/.test(line)) break;
    const doc = /^\s*\/\*\*\s*(.*?)\s*\*\/\s*$/.exec(line);
    if (doc) {
      pendingDoc = doc[1];
      continue;
    }
    const start = /^\s{4}([A-Z][A-Z0-9_]*):\s*(.*)$/.exec(line);
    if (start) {
      if (current) entries.push(finish(current));
      const trailing = /\s\/\/\s+(.*)$/.exec(start[2]);
      current = {
        key: start[1],
        expr: start[2].replace(/\s\/\/\s.*$/, "").trim(),
        doc: pendingDoc || (trailing ? trailing[1].trim() : ""),
      };
      pendingDoc = "";
      continue;
    }
    if (current) {
      const trailing = /\s\/\/\s+(.*)$/.exec(line);
      if (trailing && !current.doc) current.doc = trailing[1].trim();
      current.expr += " " + line.replace(/\s\/\/\s.*$/, "").trim();
    }
  }
  if (current) entries.push(finish(current));
  return entries;
}

function finish(e) {
  const expr = e.expr.replace(/\s+/g, " ").replace(/,\s*$/, "");
  const enumMatch = /z\.enum\(\[([^\]]*)\]\)/.exec(expr);
  const defaultMatch = /\.default\(((?:"[^"]*"|[^()]+))\)/.exec(expr);
  let type = "string";
  if (enumMatch)
    type = enumMatch[1]
      .replace(/"/g, "")
      .split(",")
      .map((s) => s.trim())
      .join(" \\| ");
  else if (/stringbool/.test(expr)) type = "true \\| false";
  else if (/coerce\.number/.test(expr)) type = "number";
  else if (/z\.url\(\)/.test(expr)) type = "URL";
  else if (/base64Bytes\((\d+)\)/.test(expr))
    type = `base64 (${/base64Bytes\((\d+)\)/.exec(expr)[1]} bytes)`;
  else if (/postgres/.test(expr)) type = "postgres:// URL";
  const required = !defaultMatch && !/\boptional\b/.test(expr) && !/\.optional\(\)/.test(expr);
  return {
    key: e.key,
    type,
    default: defaultMatch ? defaultMatch[1].replace(/^"|"$/g, "") : "",
    required,
    doc: e.doc,
  };
}

const esc = (s) => s.replace(/\|/g, "\\|");

export function renderEnvDocs(schemaSource, envExampleText) {
  const example = parseEnvExample(envExampleText);
  const entries = parseSchema(schemaSource);
  const lines = [
    START,
    "",
    "| Variable | Type | Default | Required | Notes |",
    "|---|---|---|---|---|",
  ];
  for (const e of entries) {
    const ex = example[e.key];
    const notes = e.doc || ex?.comment || "";
    const def = e.default !== "" ? `\`${esc(e.default)}\`` : "";
    lines.push(
      `| \`${e.key}\` | ${e.type} | ${def} | ${e.required ? "yes" : ""} | ${esc(notes)} |`,
    );
  }
  lines.push(
    "",
    `_${entries.length} variables, generated by \`pnpm env:docs\` from \`src/lib/env.schema.ts\`._`,
    "",
    END,
  );
  return lines.join("\n");
}

export function spliceReadme(readme, block) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error("README.md lacks the env-docs markers");
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

const invokedDirectly =
  process.argv[1] &&
  path.resolve(process.argv[1]) ===
    path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
if (invokedDirectly) {
  const block = renderEnvDocs(readFileSync(SCHEMA, "utf8"), readFileSync(ENV_EXAMPLE, "utf8"));
  const readme = existsSync(README) ? readFileSync(README, "utf8") : "";
  const next = spliceReadme(readme, block);
  if (process.argv.includes("--check")) {
    if (next !== readme) {
      console.error("README.md configuration table is stale - run `pnpm env:docs`");
      process.exit(1);
    }
    console.log("env:docs:check ok");
  } else {
    writeFileSync(README, next);
    console.log("updated README.md configuration table");
  }
}
