// Generates THIRD_PARTY_NOTICES.md from `pnpm licenses list --json --prod` plus the hand-written
// sections for bundled works that are not npm packages (the EFF wordlist, the font catalogue).
//
//   pnpm notices            rewrite THIRD_PARTY_NOTICES.md
//   pnpm notices:check      exit 1 when the file is stale (CI)
//
// `renderNotices(json)` is pure and deterministic (sorted, no dates) so it is unit-tested.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(
  path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")),
  "..",
);
const OUT = path.join(ROOT, "THIRD_PARTY_NOTICES.md");

export const HAND_SECTIONS = `## EFF Short Wordlist #1

\`src/lib/security/eff-short-wordlist.ts\` is the Electronic Frontier Foundation's "EFF Short
Wordlist #1" (1 296 words), used for generated passphrases.

- Source: https://www.eff.org/files/2016/09/08/eff_short_wordlist_1.txt (see
  https://www.eff.org/dice)
- Copyright © Electronic Frontier Foundation
- Licence: Creative Commons Attribution 3.0 Unported (CC BY 3.0),
  https://creativecommons.org/licenses/by/3.0/
- Changes: the dice numbers were dropped; the words are unchanged.

## Google Fonts (document font catalogue)

\`public/fonts/\` holds the latin subsets of 100 families vendored from their Fontsource packages
(\`src/lib/documents/fonts/catalog.ts\` lists each family, package and licence). All are under the
SIL Open Font License 1.1 except Roboto Slab (Apache License 2.0). Licence texts ship with each
\`@fontsource/<family>\` package.

## Compact ICC Profiles (sRGB output intent)

\`src/lib/einvoice/icc/sRGB-v2-magic.icc\` is the "sRGB-v2-magic" profile from Clinton Ingram's
Compact-ICC-Profiles (https://github.com/saucecontrol/Compact-ICC-Profiles), released under the
CC0 1.0 Universal public domain dedication. It is embedded as the output intent of Factur-X
PDF/A-3 files.
`;

/**
 * @param {Record<string, Array<{ name: string; versions?: string[]; version?: string; author?: string; homepage?: string }>>} json
 */
export function renderNotices(json) {
  const licences = Object.keys(json).sort((a, b) => a.localeCompare(b));
  const lines = [
    "# Third-party notices",
    "",
    "okinvo is licensed under the Apache License 2.0 (`LICENSE`, `NOTICE`). It bundles the works",
    "below under their own licences. The package list is generated by `pnpm notices` from",
    "`pnpm licenses list --json --prod`; do not edit it by hand.",
    "",
    HAND_SECTIONS.trimEnd(),
    "",
    "## Package licences (production dependencies)",
    "",
  ];
  let total = 0;
  for (const licence of licences) {
    const pkgs = [...json[licence]].sort((a, b) => a.name.localeCompare(b.name));
    lines.push(`### ${licence} (${pkgs.length})`, "");
    for (const p of pkgs) {
      total += 1;
      const versions = (p.versions ?? (p.version ? [p.version] : [])).join(", ");
      const author = p.author ? ` - ${String(p.author).replace(/\s+/g, " ").trim()}` : "";
      const home = p.homepage ? ` (${p.homepage})` : "";
      lines.push(`- ${p.name} ${versions}${author}${home}`);
    }
    lines.push("");
  }
  lines.push(`_${total} packages under ${licences.length} licences._`, "");
  return lines.join("\n");
}

function fromPnpm() {
  // A fixed command string (no user input) so Windows can resolve pnpm.cmd through the shell.
  const out = execSync("pnpm licenses list --json --prod", {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(out);
}

const invokedDirectly =
  process.argv[1] &&
  path.resolve(process.argv[1]) ===
    path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
if (invokedDirectly) {
  const rendered = renderNotices(fromPnpm());
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== rendered) {
      console.error("THIRD_PARTY_NOTICES.md is stale - run `pnpm notices`");
      process.exit(1);
    }
    console.log("notices:check ok");
  } else {
    writeFileSync(OUT, rendered);
    console.log(`wrote ${path.relative(ROOT, OUT)}`);
  }
}
