import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parse } from "yaml";

export interface Typography {
  fontFamily: string;
  fontSize: string;
  fontWeight?: number;
  lineHeight?: number | string;
  letterSpacing?: number | string;
  fontFeature?: string;
}
export interface DesignTokens {
  name: string;
  colors: Record<string, string>;
  typography?: Record<string, Typography>;
  rounded?: Record<string, string>;
  spacing?: Record<string, string | number>;
}

const HEX = /^#[0-9a-fA-F]{6}$/;

/** Font stacks per v2 §24.5 — DESIGN.md's documented substitutes for Linear's proprietary faces. */
export const FONT_STACKS = {
  sans: `"Inter Variable", "SF Pro Display", -apple-system, system-ui, "Segoe UI", Roboto, sans-serif`,
  mono: `"JetBrains Mono", "SF Mono", ui-monospace, Menlo, monospace`,
} as const;

export function parseFrontMatter(markdown: string): DesignTokens {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(markdown);
  if (!match) throw new Error("No YAML front matter found (expected a leading --- block)");
  const data = parse(match[1] ?? "") as Partial<DesignTokens> | null;
  if (!data || typeof data !== "object" || !data.colors) {
    throw new Error("front matter has no colors block");
  }
  return data as DesignTokens;
}

const px = (v: number | string): string => (typeof v === "number" ? `${v}px` : v);

export function toTokensCss(dark: DesignTokens, light: DesignTokens): string {
  const extraSections = Object.keys(light).filter(
    (k) => !["version", "name", "description", "colors"].includes(k),
  );
  if (extraSections.length > 0) {
    throw new Error(
      `DESIGN.light.md may only override colors (typography, rounded and spacing come from DESIGN.md); found: ${extraSections.join(", ")}`,
    );
  }
  for (const [k, v] of Object.entries(dark.colors)) {
    if (!HEX.test(v)) throw new Error(`DESIGN.md colors.${k} must be a 6-digit hex, got "${v}"`);
  }
  for (const [k, v] of Object.entries(light.colors)) {
    if (!(k in dark.colors)) {
      throw new Error(`DESIGN.light.md defines colors.${k}, which does not exist in DESIGN.md`);
    }
    if (!HEX.test(v))
      throw new Error(`DESIGN.light.md colors.${k} must be a 6-digit hex, got "${v}"`);
  }

  const out: string[] = [
    "/* GENERATED by scripts/design-tokens.ts from DESIGN.md + DESIGN.light.md — do not edit by hand. */",
    "@theme {",
    "  --color-*: initial;",
  ];
  for (const [k, v] of Object.entries(dark.colors)) out.push(`  --color-${k}: ${v};`);
  out.push(`  --font-sans: ${FONT_STACKS.sans};`);
  out.push(`  --font-mono: ${FONT_STACKS.mono};`);
  for (const [k, v] of Object.entries(dark.rounded ?? {})) out.push(`  --radius-${k}: ${v};`);
  // Spacing is NOT emitted as named --spacing-* tokens: names like sm/md/lg/xl collide with
  // Tailwind's container sizes inside multi-namespace utilities (max-w-sm would become 12px).
  // DESIGN.md's scale is 4px-based, which is exactly Tailwind's numeric scale, so we document
  // the mapping and components use p-3 / gap-4 / mt-6 etc.
  for (const [k, v] of Object.entries(dark.spacing ?? {})) {
    const value = px(v);
    const n = Number.parseFloat(value);
    if (!value.endsWith("px") || !Number.isInteger(n) || n % 4 !== 0 || n <= 0) {
      throw new Error(`spacing.${k} must be a positive multiple of 4px, got "${value}"`);
    }
    const step = n / 4;
    out.push(`  /* spacing ${k} = ${value} → Tailwind ${step} (p-${step}, gap-${step}, …) */`);
  }
  for (const [k, t] of Object.entries(dark.typography ?? {})) {
    out.push(`  --text-${k}: ${t.fontSize};`);
    if (t.lineHeight !== undefined) out.push(`  --text-${k}--line-height: ${t.lineHeight};`);
    if (t.fontWeight !== undefined) out.push(`  --text-${k}--font-weight: ${t.fontWeight};`);
    if (t.letterSpacing !== undefined) {
      out.push(`  --text-${k}--letter-spacing: ${px(t.letterSpacing)};`);
    }
  }
  // :root[…] outranks Tailwind's own :root emission of the dark values.
  out.push("}", "", `:root[data-theme="light"] {`);
  for (const [k, v] of Object.entries(light.colors)) out.push(`  --color-${k}: ${v};`);
  out.push("}");
  return out.join("\n") + "\n";
}

/**
 * tailwind-merge classifies unknown `text-*` classes as colours, so `cn("text-app-label", "text-ink")`
 * would drop the size. This module lets src/lib/utils.ts register every typography key as a font size.
 */
export function toTypographyKeysTs(dark: DesignTokens): string {
  const keys = Object.keys(dark.typography ?? {});
  return [
    "// GENERATED by scripts/design-tokens.ts from DESIGN.md — do not edit by hand.",
    "// tailwind-merge must treat `text-<key>` for these keys as font sizes, not text colours (src/lib/utils.ts).",
    "export const TYPOGRAPHY_KEYS = [",
    ...keys.map((k) => `  "${k}",`),
    "] as const;",
    "",
  ].join("\n");
}

/**
 * A typed map of both themes' colours for the few places that cannot read CSS variables: the web
 * manifest and image generation. Light inherits every key it does not override.
 */
export function toColorsTs(dark: DesignTokens, light: DesignTokens): string {
  const ident = /^[A-Za-z_$][\w$]*$/;
  const block = (colors: Record<string, string>): string[] =>
    Object.entries(colors).map(
      ([k, v]) => `    ${ident.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)},`,
    );
  return [
    "// GENERATED by scripts/design-tokens.ts from DESIGN.md and DESIGN.light.md — do not edit by hand.",
    "// For code that cannot use the CSS tokens (manifest, image generation). Components use tokens.css.",
    "export const DESIGN_COLORS = {",
    "  dark: {",
    ...block(dark.colors),
    "  },",
    "  light: {",
    ...block({ ...dark.colors, ...light.colors }),
    "  },",
    "} as const;",
    "",
  ].join("\n");
}

function main(): void {
  const root = resolve(import.meta.dirname, "..");
  const dark = parseFrontMatter(readFileSync(resolve(root, "DESIGN.md"), "utf8"));
  const light = parseFrontMatter(readFileSync(resolve(root, "DESIGN.light.md"), "utf8"));
  const outputs: { target: string; content: string }[] = [
    { target: resolve(root, "src/app/tokens.css"), content: toTokensCss(dark, light) },
    {
      target: resolve(root, "src/lib/typography-keys.generated.ts"),
      content: toTypographyKeysTs(dark),
    },
    {
      target: resolve(root, "src/lib/design-colors.generated.ts"),
      content: toColorsTs(dark, light),
    },
  ];
  if (process.argv.includes("--check")) {
    for (const { target, content } of outputs) {
      const current = existsSync(target) ? readFileSync(target, "utf8") : "";
      if (current !== content) {
        console.error(`${target} is stale — run \`pnpm design:tokens\` and commit the result`);
        process.exit(1);
      }
    }
    console.log("generated design files are up to date");
    return;
  }
  for (const { target, content } of outputs) {
    writeFileSync(target, content);
    console.log(`wrote ${target}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
