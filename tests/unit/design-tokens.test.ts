import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  parseFrontMatter,
  toColorsTs,
  toTokensCss,
  toTypographyKeysTs,
} from "../../scripts/design-tokens";

const dark = `---
name: t
colors:
  canvas: "#010102"
  ink: "#f7f8f8"
typography:
  app-body:
    fontFamily: Inter
    fontSize: 14px
    fontWeight: 400
    lineHeight: 1.5
    letterSpacing: 0
rounded:
  md: 8px
spacing:
  md: 16px
---
## Overview
`;
const light = `---
name: t-light
colors:
  canvas: "#ffffff"
---
`;

describe("parseFrontMatter", () => {
  it("returns the YAML tokens", () => {
    const t = parseFrontMatter(dark);
    expect(t.colors.canvas).toBe("#010102");
    expect(t.rounded?.md).toBe("8px");
  });
  it("throws without front matter", () => {
    expect(() => parseFrontMatter("# no tokens")).toThrow(/front matter/);
  });
});

describe("toTokensCss", () => {
  const css = toTokensCss(parseFrontMatter(dark), parseFrontMatter(light));
  it("emits dark colours inside @theme and resets Tailwind's palette", () => {
    expect(css).toContain("@theme {");
    expect(css).toContain("  --color-*: initial;");
    expect(css).toContain("  --color-canvas: #010102;");
  });
  it("emits light overrides under [data-theme=light] only for declared keys", () => {
    const lightBlock = css.split('[data-theme="light"] {')[1] ?? "";
    expect(lightBlock).toContain("--color-canvas: #ffffff;");
    expect(lightBlock).not.toContain("--color-ink");
  });
  it("emits typography as --text-* with sub-values and the radius scale", () => {
    expect(css).toContain("  --text-app-body: 14px;");
    expect(css).toContain("  --text-app-body--line-height: 1.5;");
    expect(css).toContain("  --text-app-body--font-weight: 400;");
    expect(css).toContain("  --text-app-body--letter-spacing: 0px;");
    expect(css).toContain("  --radius-md: 8px;");
  });
  it("maps DESIGN.md spacing onto Tailwind's numeric scale instead of named tokens", () => {
    // Named spacing tokens (sm/md/lg/xl) collide with Tailwind's container sizes in max-w-*/w-*:
    // `max-w-sm` would resolve to 12px. The scale is 4px-based, so p-3 == DESIGN.md `sm`.
    expect(css).not.toContain("--spacing-md");
    expect(css).toContain("spacing md = 16px → Tailwind 4 (p-4, gap-4, …)");
  });
  it("rejects a spacing token that is not a multiple of 4px", () => {
    const bad = parseFrontMatter(
      `---\nname: x\ncolors:\n  canvas: "#010102"\nspacing:\n  odd: 10px\n---\n`,
    );
    expect(() => toTokensCss(bad, parseFrontMatter(light))).toThrow(/spacing\.odd/);
  });
  it("rejects a light token that does not exist in dark (typo protection)", () => {
    const bad = parseFrontMatter(`---\nname: x\ncolors:\n  canvsa: "#ffffff"\n---\n`);
    expect(() => toTokensCss(parseFrontMatter(dark), bad)).toThrow(/colors\.canvsa/);
  });
  it("rejects non-colour sections in the light file instead of ignoring them", () => {
    const bad = parseFrontMatter(
      `---\nname: x\ncolors:\n  canvas: "#ffffff"\ntypography:\n  app-body:\n    fontFamily: Inter\n    fontSize: 14px\n---\n`,
    );
    expect(() => toTokensCss(parseFrontMatter(dark), bad)).toThrow(
      /DESIGN\.light\.md.*only.*colors/,
    );
  });
  it("rejects non-hex colours", () => {
    const bad = parseFrontMatter(`---\nname: x\ncolors:\n  canvas: "white"\n---\n`);
    expect(() => toTokensCss(bad, parseFrontMatter(light))).toThrow(/canvas/);
  });
});

describe("repository files", () => {
  const root = resolve(__dirname, "../..");
  const d = parseFrontMatter(readFileSync(resolve(root, "DESIGN.md"), "utf8"));
  const l = parseFrontMatter(readFileSync(resolve(root, "DESIGN.light.md"), "utf8"));
  it("light file overrides every surface, ink, hairline and semantic token", () => {
    const required = Object.keys(d.colors).filter((k) =>
      /^(canvas|surface-|hairline|ink|semantic-|primary|link)/.test(k),
    );
    for (const k of required) expect(l.colors, k).toHaveProperty(k);
  });
  it("committed src/app/tokens.css is current", () => {
    const committed = readFileSync(resolve(root, "src/app/tokens.css"), "utf8");
    expect(committed).toBe(toTokensCss(d, l));
  });
  it("exports the typography keys as a TS module so tailwind-merge knows text-<key> is a size", () => {
    const ts = toTypographyKeysTs(d);
    expect(ts).toContain('"app-label"');
    expect(ts).toContain('"display-md"');
    expect(ts).toMatch(/export const TYPOGRAPHY_KEYS = \[[\s\S]*\] as const;/);
    const committed = readFileSync(resolve(root, "src/lib/typography-keys.generated.ts"), "utf8");
    expect(committed).toBe(ts);
  });
});

describe("toColorsTs", () => {
  it("emits a typed map of both themes so app code never carries a hex literal", () => {
    const ts = toColorsTs(parseFrontMatter(dark), parseFrontMatter(light));
    expect(ts).toContain("GENERATED by scripts/design-tokens.ts");
    expect(ts).toContain("export const DESIGN_COLORS = {");
    expect(ts).toContain(["  dark: {", '    canvas: "#010102",', '    ink: "#f7f8f8",'].join("\n"));
    // light inherits dark values for keys it does not override
    expect(ts).toContain(
      ["  light: {", '    canvas: "#ffffff",', '    ink: "#f7f8f8",'].join("\n"),
    );
    expect(ts).toContain("} as const;");
  });
});

describe("accent blocks", () => {
  const darkWithAccents = `---
name: t
colors:
  primary: "#87d9a8"
  on-primary: "#17191e"
  primary-hover: "#79cf9b"
  primary-focus: "#87d9a8"
  accent-rose-primary: "#f2a7b8"
  accent-rose-on-primary: "#17191e"
  accent-rose-primary-hover: "#ea91a5"
  accent-rose-primary-focus: "#f2a7b8"
typography: {}
---
`;
  const lightWithAccents = `---
name: t-light
colors:
  accent-rose-primary: "#ea8ea3"
---
`;
  it("emits one data-accent override per accent, with light inheriting what it does not set", () => {
    const css = toTokensCss(parseFrontMatter(darkWithAccents), parseFrontMatter(lightWithAccents));
    expect(css).toContain(
      [
        ':root[data-accent="rose"] {',
        "  --color-primary: #f2a7b8;",
        "  --color-on-primary: #17191e;",
        "  --color-primary-hover: #ea91a5;",
        "  --color-primary-focus: #f2a7b8;",
        "}",
      ].join("\n"),
    );
    expect(css).toContain(
      [':root[data-accent="rose"][data-theme="light"] {', "  --color-primary: #ea8ea3;", "}"].join(
        "\n",
      ),
    );
    expect(css).toContain("--color-accent-rose-primary: #f2a7b8;"); // swatches can use the raw token
  });
  it("refuses an accent that lacks one of the four tokens", () => {
    const broken = darkWithAccents.replace('  accent-rose-on-primary: "#17191e"\n', "");
    expect(() => toTokensCss(parseFrontMatter(broken), parseFrontMatter(lightWithAccents))).toThrow(
      /accent-rose.*on-primary/,
    );
  });
});
