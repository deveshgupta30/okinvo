export type FontId = (typeof FONT_CATALOG)[number]["id"];

export const FONT_IDS = FONT_CATALOG.map((f) => f.id) as [FontId, ...FontId[]];

const BY_ID: ReadonlyMap<string, FontEntry> = new Map(FONT_CATALOG.map((f) => [f.id, f]));

/** The catalogue entry for a font id; ids are validated by the schema before they get here. */
export function fontFamily(id: FontId): FontEntry {
  const f = BY_ID.get(id);
  if (!f) throw new Error(`unknown font id ${id}`);
  return f;
}

export function isFontId(v: unknown): v is FontId {
  return typeof v === "string" && BY_ID.has(v);
}
